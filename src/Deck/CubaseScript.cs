using System.Globalization;
using System.Text;
using System.Text.Json;

namespace MIDIRouter.Deck;

/// <summary>
/// Writes a deck as a Cubase / Nuendo MIDI Remote driver script (midiremote_api_v1, ES5). The surface mirrors the deck
/// grid and every control is bound to the MIDI it sends; mapping to Cubase functions is left to the Mapping Assistant.
/// </summary>
internal static class CubaseScript
{
	public const string Vendor = "MIDIRouter";

	// One deck cell is a 2 x 2 block of surface units: the control, and a label strip under it.
	private const double Cell = 2;
	private const double LabelHeight = 0.6;
	private const double SmallLabelHeight = 0.4;

	// Driver Scripts folders of the Steinberg apps that have run at least once, e.g. Documents/Steinberg/Cubase.
	public static IReadOnlyList<string> DriverScriptFolders()
	{
		var steinberg = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "Steinberg");
		try
		{
			return Directory.Exists(steinberg)
				? [.. Directory.GetDirectories(steinberg)
					.Select(app => Path.Combine(app, "MIDI Remote", "Driver Scripts"))
					.Where(Directory.Exists)
					.Order(StringComparer.OrdinalIgnoreCase)]
				: [];
		}
		catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
		{
			return [];
		}
	}

	// "Local", not "Public": Cubase overwrites Public on start.
	public static string RelativePath(DeckLayout deck) =>
		Path.Combine("Local", Vendor, deck.Id, $"{Vendor}_{deck.Id}.js");

	// portName is the port the DAW sees: the router's virtual port or loopback port, which is both an input and an output.
	public static string Generate(DeckLayout deck, string portName)
	{
		var js = new StringBuilder();
		js.AppendLine(Invariant($"// Generated by MIDI Router from the deck {Quote(deck.Name)}. Export again after changing the deck:"));
		js.AppendLine("// edits made here are overwritten.");
		js.AppendLine("var midiremote_api = require('midiremote_api_v1')");
		js.AppendLine();
		js.AppendLine(Invariant($"var deviceDriver = midiremote_api.makeDeviceDriver({Quote(Vendor)}, {Quote(deck.Id)}, {Quote("MIDI Router")})"));
		js.AppendLine();
		js.AppendLine("var midiInput = deviceDriver.mPorts.makeMidiInput()");
		js.AppendLine("var midiOutput = deviceDriver.mPorts.makeMidiOutput()");
		js.AppendLine();
		js.AppendLine("deviceDriver.makeDetectionUnit().detectPortPair(midiInput, midiOutput)");
		js.AppendLine(Invariant($"\t.expectInputNameEquals({Quote(portName)})"));
		js.AppendLine(Invariant($"\t.expectOutputNameEquals({Quote(portName)})"));
		js.AppendLine();
		js.AppendLine("var surface = deviceDriver.mSurface");
		js.AppendLine(Invariant($"var page = deviceDriver.mMapping.makePage({Quote(deck.Name)})"));

		foreach (var (control, index) in deck.Controls.Select((control, index) => (control, index)))
		{
			js.AppendLine();
			js.AppendLine(Invariant($"// {Quote(control.Label)}: {DeckLayout.Describe(control)}, channel {control.Channel}"));

			// The API has no program change binding.
			if (control.Message == DeckMessage.ProgramChange)
			{
				js.AppendLine("// not exported: MIDI Remote can't bind a program change");
				continue;
			}

			var element = Invariant($"control{index + 1}");

			// A small button is the top or bottom half of its cell, with a narrower label strip.
			var (x, y, width, height, labelHeight) = control.Kind == DeckControlKind.SmallButton
				? (control.X * Cell, (control.Y * Cell) + (control.Slot * Cell / 2), Cell, (Cell / 2) - SmallLabelHeight, SmallLabelHeight)
				: (control.X * Cell, control.Y * Cell, control.Width * Cell, (control.Height * Cell) - LabelHeight, LabelHeight);
			var factory = control switch
			{
				{ IsSlider: true } => "makeFader",
				{ Kind: DeckControlKind.Button, Message: DeckMessage.Note } => "makeTriggerPad",
				_ => "makeButton",
			};
			var binding = control.Message == DeckMessage.Note
				? Invariant($"bindToNote({control.Channel - 1}, {control.Number})")
				: Invariant($"bindToControlChange({control.Channel - 1}, {control.Number})");

			js.AppendLine(Invariant($"var {element} = surface.{factory}({x}, {y}, {width}, {height})"));
			if (control.IsSlider)
			{
				js.AppendLine(Invariant($"{element}.{(control.Kind == DeckControlKind.VerticalSlider ? "setTypeVertical" : "setTypeHorizontal")}()"));
			}

			js.AppendLine(Invariant($"{element}.mSurfaceValue.mMidiBinding.setInputPort(midiInput).{binding}"));
			js.AppendLine(Invariant(
				$"page.setLabelFieldText(surface.makeLabelField({x}, {y + height}, {width}, {labelHeight}).relateTo({element}), {Quote(control.Label)})"));
		}

		return js.ToString();
	}

	// A JSON string is a valid ES5 string literal; non-ASCII comes out as \u escapes.
	private static string Quote(string text) => JsonSerializer.Serialize(text);

	private static string Invariant(FormattableString text) => text.ToString(CultureInfo.InvariantCulture);
}
