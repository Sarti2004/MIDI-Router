using System.Globalization;
using System.Text;
using System.Text.Json;

namespace MIDIRouter.Deck;

/// <summary>
/// Writes the virtual device as a Cubase / Nuendo MIDI Remote driver script (midiremote_api_v1, ES5). The surface
/// mirrors the device's grid and every control is bound to the MIDI it sends, both ways: Cubase sends the control's
/// value back, which lights the device's buttons and moves its faders. Mapping to Cubase functions is left to the
/// Mapping Assistant.
/// </summary>
internal static class CubaseScript
{
	public const string Vendor = "MIDIRouter";

	// One grid cell is a 2 x 2 block of surface units: the control, and a label strip under it.
	private const double Cell = 2;
	private const double LabelHeight = 0.6;
	private const double SmallLabelHeight = 0.4;

	// Driver Scripts folders of the Steinberg apps that have run at least once, e.g. Documents/Steinberg/Cubase.
	public static IReadOnlyList<string> DriverScriptFolders()
	{
		var steinberg = Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.MyDocuments), "Steinberg");
		try
		{
			return Directory.Exists(steinberg)
				? [.. Directory.GetDirectories(steinberg)
					.Select(app => Path.Combine(app, "MIDI Remote", "Driver Scripts"))
					.Where(Directory.Exists)
					.Order(StringComparer.OrdinalIgnoreCase)]
				: [];
		}
		catch (Exception ex) when (ex is IOException or UnauthorizedAccessException)
		{
			return [];
		}
	}

	// "Local", not "Public": Cubase overwrites Public on start.
	public static string RelativePath() =>
		Path.Combine("Local", Vendor, VirtualDevice.Id, $"{Vendor}_{VirtualDevice.Id}.js");

	// Cubase finds the device by its ports, named after it while it is switched on.
	public static string Generate(VirtualDevice device)
	{
		var portName = device.Name;
		var js = new StringBuilder();
		js.AppendLine(Invariant($"// Generated by MIDI Router from the virtual device {Quote(device.Name)}. Export again after changing it:"));
		js.AppendLine("// edits made here are overwritten.");
		js.AppendLine("var midiremote_api = require('midiremote_api_v1')");
		js.AppendLine();
		js.AppendLine(Invariant($"var deviceDriver = midiremote_api.makeDeviceDriver({Quote(Vendor)}, {Quote(VirtualDevice.Id)}, {Quote("MIDI Router")})"));
		js.AppendLine();
		js.AppendLine("var midiInput = deviceDriver.mPorts.makeMidiInput()");
		js.AppendLine("var midiOutput = deviceDriver.mPorts.makeMidiOutput()");
		js.AppendLine();
		js.AppendLine("deviceDriver.makeDetectionUnit().detectPortPair(midiInput, midiOutput)");
		js.AppendLine(Invariant($"\t.expectInputNameEquals({Quote(portName)})"));
		js.AppendLine(Invariant($"\t.expectOutputNameEquals({Quote(portName)})"));
		js.AppendLine();
		js.AppendLine("var surface = deviceDriver.mSurface");
		js.AppendLine(Invariant($"var page = deviceDriver.mMapping.makePage({Quote(device.Name)})"));

		foreach (var (element, index) in device.Elements.Select((element, index) => (element, index)))
		{
			var binding = DeviceActions.Binding(element);
			js.AppendLine();
			js.AppendLine(Invariant($"// {Quote(element.Label)}: {binding?.ToString() ?? element.ActionId}"));

			// The API has no program change binding.
			if (binding is not { Kind: not MidiMessageKind.ProgramChange } midi)
			{
				js.AppendLine("// not exported: MIDI Remote can only bind notes and CCs");
				continue;
			}

			var name = Invariant($"control{index + 1}");

			// A small button is the top or bottom half of its cell, with a narrower label strip.
			var (x, y, width, height, labelHeight) = element.Kind == DeviceElementKind.SmallButton
				? (element.X * Cell, (element.Y * Cell) + (element.Slot * Cell / 2), Cell, (Cell / 2) - SmallLabelHeight, SmallLabelHeight)
				: (element.X * Cell, element.Y * Cell, element.Width * Cell, (element.Height * Cell) - LabelHeight, LabelHeight);
			var factory = element switch
			{
				{ IsSlider: true } => "makeFader",
				{ Kind: DeviceElementKind.Button } when midi.Kind == MidiMessageKind.Note => "makeTriggerPad",
				_ => "makeButton",
			};
			var bind = midi.Kind == MidiMessageKind.Note
				? Invariant($"bindToNote({midi.Channel - 1}, {midi.Number})")
				: Invariant($"bindToControlChange({midi.Channel - 1}, {midi.Number})");

			js.AppendLine(Invariant($"var {name} = surface.{factory}({x}, {y}, {width}, {height})"));
			if (element.IsSlider)
			{
				js.AppendLine(Invariant($"{name}.{(element.Kind == DeviceElementKind.VerticalSlider ? "setTypeVertical" : "setTypeHorizontal")}()"));
			}

			js.AppendLine(Invariant($"{name}.mSurfaceValue.mMidiBinding.setInputPort(midiInput).setOutputPort(midiOutput).{bind}"));
			js.AppendLine(Invariant(
				$"page.setLabelFieldText(surface.makeLabelField({x}, {y + height}, {width}, {labelHeight}).relateTo({name}), {Quote(element.Label)})"));
		}

		return js.ToString();
	}

	// A JSON string is a valid ES5 string literal; non-ASCII comes out as \u escapes.
	private static string Quote(string text) => JsonSerializer.Serialize(text);

	private static string Invariant(FormattableString text) => text.ToString(CultureInfo.InvariantCulture);
}
